def find_topic(slug):
    return next((topic for topic in TOPICS if topic["slug"] == slug), None)


@app.context_processor
def inject_site_data():
    return {"site_name": "سازوکار جهان"}


@app.route("/")
def home():
    return render_template("index.html", topics=TOPICS)


@app.route("/topic/<slug>")
def topic(slug):
    selected_topic = find_topic(slug)
    if selected_topic is None:
        abort(404)
    related_topics = [item for item in TOPICS if item["slug"] != slug][:3]
    return render_template("topic.html", topic=selected_topic, related_topics=related_topics)


@app.route("/article/<slug>")
def article(slug):
    if slug != ARTICLE["slug"]:
        abort(404)
    return render_template("article.html", article=ARTICLE)


@app.errorhandler(404)
def page_not_found(_error):
    return render_template("404.html"), 404


